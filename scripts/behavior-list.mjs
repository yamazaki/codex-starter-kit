#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {evaluateResults,minimumRuns} from "./behavior-eval.mjs";
import {remediationState} from "./lib/behavior-remediation.mjs";
import {verifiedReplacementEvidence} from "./lib/behavior-evidence-gate.mjs";
import {supportedBehaviorVersion} from './lib/behavior-version.mjs';

const root=path.resolve(import.meta.dirname,"..");
const suite=JSON.parse(fs.readFileSync(path.join(root,"docs/testing/behavior-cases.json")));
const notes=JSON.parse(fs.readFileSync(path.join(root,"docs/testing/behavior-result-notes.json")));
const marker="<!-- Generated by behavior-list.mjs. Do not edit manually. -->";
const cell=(text)=>String(text).replaceAll("|","\\|").replaceAll("\n"," ");
const minimum=minimumRuns;
const labels={PASS:"合格",IN_PROGRESS:"一部確認",NOT_RUN:"未実施",FAIL:"不合格",BLOCKED:"実施不能"};

export function renderCatalog() {
  const templates=JSON.parse(fs.readFileSync(path.join(root,"docs/testing/automation-pilot.json"))).cases;
  const rows=suite.cases.map(c=>{
    const template=templates.find(t=>t.id===c.id);
    const target=c.id==='runtime-hook'?"専用Hook runner＋正式な信頼画面":c.id==='runtime-routing'?"課題から自動選択（名前指定なし）":template?.skill??template?.agent??(template?.kitRules?"配布AGENTS.md（日本語）":['hook-safety','config-settings'].includes(c.id)?"配布CLI（モデルなし）":"テンプレート未対応");
    return `| ${c.id} | ${cell(c.covers.join("、"))} | ${cell(target)} | ${cell(c.task)} | ${cell(c.checks.join("／"))} | ${cell(c.boundary)} | ${minimum(c.id)}/${minimum(c.id)} |`;
  });
  return [marker,"# 動作確認一覧","",
    `対象: ${suite.kitVersion} / 本家commit ${suite.upstreamCommit}。採用機能の代表課題${suite.cases.length}件。除外機能は[移植概要](../../upstream/assessments/0.78.1-porting-overview.md)で理由を確認する。`,"",
    "試験定義の正本は[behavior-cases.json](behavior-cases.json)。正常系と境界試験は別の初期状態・新規セッションで実施する。重要ケースは各3回、それ以外は各1回から開始する。対象の移植管理IDとCodexでの名前を区別する。テンプレート未対応は未移植という意味ではなく、専用の実行手順を追加する必要がある。下表は試験仕様であり実行済みを意味しない。[結果一覧](RESULTS_SUMMARY.md)を参照。","",
    "| ID | 対象機能の移植管理ID | Codex側の自動実行対象 | 正常系の課題 | 確認する条件 | 境界試験 | 必要回数（正常/境界） |",
    "| --- | --- | --- | --- | --- | --- | --- |",rows.join("\n"),""
  ].join("\n");
}

export function rawEvidenceNotice(data) {
  if (data.evidenceAvailability?.priorRaw !== 'UNAVAILABLE') return '';
  return verifiedReplacementEvidence(data, suite.cases, minimumRuns)
    ? '過去の一時保存rawログは失われたままである。全55ケースの必要反復について、新規試験または保存済みの原証拠と独立採点を確認し、代替証拠として記録した。過去ログの復元やオーナーの受入・Public化の承認を意味しない。\n\n'
    : '過去の一時保存rawログは現在再読できない。採点snapshotは保持しているが、公開判断には再試験またはオーナーの明示判断が必要。\n\n';
}

export function renderSummary(data,date) {
  if(!/^\d{4}-\d{2}-\d{2}$/.test(date))throw new Error("snapshot date required");
  if(data.schemaVersion!==1||!supportedBehaviorVersion(data.baseline?.kitVersion)||data.baseline?.upstreamCommit!==suite.upstreamCommit||data.records?.length!==suite.cases.length||new Set(data.records.map(r=>r.id)).size!==suite.cases.length||data.records.some(r=>!suite.cases.some(c=>c.id===r.id)||!labels[r.status]))throw new Error("invalid result snapshot");
  const gate=evaluateResults(data);
  const rows=suite.cases.map(c=>{
    const r=data.records.find(r=>r.id===c.id);
    const remediation=remediationState(r,c.checks.length+3);
    const required=remediation.totalFailures?Math.max(3,minimum(c.id)):minimum(c.id);
    const groups=new Map();
    for(const a of remediation.activeAttempts){
      if(a.verdict!=="PASS"||a.sourceReview!=="CONFIRMED"||!a.session||!a.reviewer||!a.evidence?.length||!a.sourceRequirements?.length||!a.model||!a.surface||a.criteria?.length!==c.checks.length+3||a.criteria.some(v=>v!=="PASS"))continue;
      const k=`${a.model}\n${a.surface}\n${a.subjectDigest??'legacy'}\n${a.cliVersion??'legacy'}`;
      if(!groups.has(k))groups.set(k,{normal:new Set(),boundary:new Set()});
      if(["normal","boundary"].includes(a.variant))groups.get(k)[a.variant].add(a.session);
    }
    const best=[...groups.values()].sort((a,b)=>Math.min(b.normal.size,b.boundary.size)-Math.min(a.normal.size,a.boundary.size)||b.normal.size+b.boundary.size-a.normal.size-a.boundary.size)[0];
    const complete=!gate.reasons.some(reason=>reason.startsWith(`${c.id}:`));
    const state=complete?"合格":r.status==="PASS"?"追加確認が必要":labels[r.status];
    const incidents=r.executionIncidents??[];
    const pendingIssues=(r.issues??[]).some(i=>i.status!=="RESOLVED");
    return `| ${c.id} | ${state} | ${best?.normal.size??0}/${required} | ${best?.boundary.size??0}/${required} | ${(r.observations??[]).length} | ${incidents.filter(i=>i.status!=="RETESTED").length}/${incidents.length} | ${remediation.totalFailures-remediation.resolved.size}/${remediation.totalFailures} | ${remediation.corrected.size}/${(r.gradingCorrections??[]).length} | ${pendingIssues?"移植・配布内容に未解決の指摘あり。":(complete||r.status==="FAIL")?cell((r.status==="FAIL"?notes[`${c.id}:failure`]:undefined)??notes[c.id]??"採点済みの結果を確認。"):r.status==="NOT_RUN"?"課題の具体化・実行・採点が必要。":"未完了の条件・反復・証拠を確認。"} |`;
  });
  return `${marker}\n# 動作確認結果一覧\n\n- 更新日: ${date}\n- 対象: ${data.baseline.kitVersion} / 本家commit ${suite.upstreamCommit}\n${data.candidateVerification?"- 検証対象にはローカル修正candidateを含む。既存Release・本番インストールへの反映とは別。\n":""}- 完了: ${gate.passed}/${gate.total}ケース\n- 全体のオーナーレビュー準備: ${gate.readyForOwnerReview?"完了":"未完了"}（Public化の承認とは別）\n\n${rawEvidenceNotice(data)}[動作確認一覧](CASE_CATALOG.md)と[検証方法](BEHAVIOR_VALIDATION.md)に対応するスナップショット。構造テストや起動確認だけで合格にしない。同じモデル・実行環境の評価済み試行だけを反復へ数え、表には一つの組合せを示す。desktopとCLIを合算しない。生ログ・認証情報・個人パス・セッションIDは公開用の表へ載せない。証拠付き詳細記録はprivate保守側で管理する。\n\n「一部観察」は信頼済みHookの拒否など、ケースの全条件を満たさない確認。反復回数には数えない。「実行障害」は未解決/累計。解決後も失敗記録を消さない。「不合格履歴」は能力試行の未解消/累計であり、変更された指示と正常・境界各3回の評価済み再試験・明示reviewが揃うまで解消しない。元のFAIL判定は保持する。「採点訂正」はnative原証拠の収集漏れを確認した評価側の誤りで、能力FAILと区別する。元の採点を残し、明示reviewで実行結果との一致を確認した訂正だけを反映する。合格は指定した代表課題の範囲であり、全機能同等や全用途の保証ではない。結果の短い説明はレビュー済みの説明用データから、合格または不合格の採点済みケースへ表示する。\n\n| ID | ケース判定 | 正常系の合格/必要 | 境界試験の合格/必要 | 一部観察 | 実行障害（未解決/累計） | 不合格履歴（未解消/累計） | 採点訂正（反映/累計） | 確認結果・残る範囲 |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n${rows.join("\n")}\n\n## 確認範囲の制約\n\nCLIでは個人スキルが追加で見える条件がある。DB・ブラウザを持たない課題は設計や制約の判断であり実機試験ではない。文章スキルの適切な原文の保持、prompt-patternsの曖昧な依頼整理も代表課題に限る。既存検証でproject外のnpmログ書込みは未確認だったため、環境全体の無変更は断定しない。残るケースの未実施を合格へ置き換えない。\n`;
}

export function validateReportTarget(baseRoot,relative,json=false) {
  baseRoot=path.resolve(baseRoot);
  if(!["docs/testing/CASE_CATALOG.md","docs/testing/RESULTS_SUMMARY.md","internal/testing/RESULTS.json","internal/testing/RESULTS.md"].includes(relative))throw new Error("unknown report target");
  const target=path.join(baseRoot,relative);
  let ancestor=path.dirname(target);
  while(ancestor!==baseRoot){if(fs.existsSync(ancestor)&&fs.lstatSync(ancestor).isSymbolicLink())throw new Error("symlink report ancestor");ancestor=path.dirname(ancestor);}
  if(fs.existsSync(target)){
    if(!fs.lstatSync(target).isFile()||fs.lstatSync(target).isSymbolicLink())throw new Error("unsafe report target");
    const prior=fs.readFileSync(target,"utf8");
    if(json?JSON.parse(prior)._generatedBy!=="behavior-list.mjs":!prior.startsWith(marker))throw new Error("report target is user-owned");
  }
  return target;
}

function generatedWrite(relative,content,json=false) {
  const target=validateReportTarget(root,relative,json);
  fs.mkdirSync(path.dirname(target),{recursive:true});
  fs.writeFileSync(target,content,{mode:relative.startsWith("internal/")?0o600:0o644});
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  try{
    const [input,date]=process.argv.slice(2);
    if(!input||!path.isAbsolute(input)||fs.realpathSync(input)!==path.resolve(input)||!fs.lstatSync(input).isFile())throw new Error("regular absolute results path required");
    const userHome=process.env.HOME;
    const protectedRoots=[...(userHome?[path.join(userHome,".codex"),path.join(userHome,".agents")]:[]),...(process.env.CODEX_HOME?[process.env.CODEX_HOME]:[])];
    if(protectedRoots.some(p=>input===p||input.startsWith(`${p}${path.sep}`)))throw new Error("do not read credential or user runtime roots");
    if(!fs.existsSync(path.join(root,"internal/session-history")))throw new Error("private checkout required; do not create internal in a public clone");
    const data=JSON.parse(fs.readFileSync(input));
    const summary=renderSummary(data,date);
    for(const relative of ["docs/testing/CASE_CATALOG.md","docs/testing/RESULTS_SUMMARY.md","internal/testing/RESULTS.json","internal/testing/RESULTS.md"])validateReportTarget(root,relative,relative.endsWith(".json"));
    generatedWrite("docs/testing/CASE_CATALOG.md",renderCatalog());
    generatedWrite("docs/testing/RESULTS_SUMMARY.md",summary);
    generatedWrite("internal/testing/RESULTS.json",JSON.stringify({...data,_generatedBy:"behavior-list.mjs",snapshotDate:date},null,2)+"\n",true);
    const details=data.records.map(r=>`## ${r.id}\n\n状態: ${labels[r.status]}\n\n${(r.attempts??[]).map(a=>`- ${cell(a.variant)} / ${cell(a.verdict)} / ${cell(a.model)} / ${cell(a.surface)} / session: ${cell(a.session)}\n  - 根拠: ${cell((a.evidence??[]).join("、"))}`).join("\n")}\n\n一部観察: ${(r.observations??[]).length}、実行障害: ${(r.executionIncidents??[]).length}\n`).join("\n");
    generatedWrite("internal/testing/RESULTS.md",`${marker}\n# 動作確認結果の詳細（非公開）\n\n更新日: ${date}。採点・証拠参照・実行障害・一部観察の正本は[RESULTS.json](RESULTS.json)。生ログは取り込まない。公開用集計は[結果一覧](../../docs/testing/RESULTS_SUMMARY.md)。\n\n${details}`);
    console.log(JSON.stringify({cases:suite.cases.length,completed:evaluateResults(data).passed,privateSnapshotSaved:true}));
  }catch(e){console.error(e instanceof SyntaxError?"invalid result JSON; report not generated":e.message);process.exitCode=1;}
}
